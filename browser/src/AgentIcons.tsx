export function AgentIcon({ provider, size = 12 }: { provider?: string; size?: number }) {
  if (!provider) return null;
  if (provider === "claude") return <ClaudeIcon size={size} />;
  if (provider === "codex") return <CodexIcon size={size} />;
  if (provider === "gemini" || provider === "antigravity") return <GeminiIcon size={size} />;
  // Unknown providers get a letter badge so the icon never silently vanishes.
  return (
    <span
      style={{ width: size, height: size, fontSize: size * 0.65 }}
      className="inline-flex items-center justify-center rounded-full bg-ink-4/20 text-ink-3 mono uppercase leading-none"
    >
      {provider[0]}
    </span>
  );
}
